#!/usr/bin/env bash
# The last step of every image build (build.sh, dx.sh, nvidia.sh): leave nothing behind that `bootc container lint --fatal-warnings` warns about.
#   /boot         must be empty (extlinux and the like come from packages)
#   /run, /tmp    are runtime-only: whatever package scriptlets left there is removed
#   /var          must not carry image content: anything RPM scriptlets put there is rebuilt at boot instead (a tmpfiles.d entry per directory,
#                 `C` copies of files from /usr/share/factory/var, `L+` for symlinks), and package-manager state is dropped. /var/cache and /var/log are
#                 cache mounts of the build and are left alone.
# The lint prints exactly which paths it objects to; this script generates /usr/lib/tmpfiles.d/octarine-var.conf from what is really there, so
# a package that ships a new /var directory needs no manual list.
set -euo pipefail
# Log group (folded in the GitHub Actions build log, plain text elsewhere); the trap closes it however the script ends and prints an
# "::error::" line outside it on failure. Exit status unchanged.
echo "::group::final-cleanup.sh"
trap 'rc=$?; echo "::endgroup::"; if (( rc != 0 )); then echo "::error::final-cleanup.sh failed (exit ${rc})"; fi' EXIT
shopt -s dotglob nullglob

rm -rf /boot/*
for d in /run /tmp; do find "${d}" -mindepth 1 -maxdepth 1 -exec rm -rf {} + 2>/dev/null || true; done

# package-manager state and crash dumps are no image content
rm -rf /var/lib/dnf /var/lib/PackageKit /var/lib/rpm-state /var/crash /var/tmp/*

conf=/usr/lib/tmpfiles.d/octarine-var.conf
factory=/usr/share/factory/var
# a later layer (dx, nvidia) adds its entries to the file of the layer below
[[ -s "${conf}" ]] || echo "# Generated by build_files/final-cleanup.sh at image build: the /var content the packages created, rebuilt at boot (bootc lint wants /var empty in the image)." >"${conf}"
n=0
while IFS= read -r -d '' p; do
	case "${p}" in *[[:space:]%]*)
		echo "final-cleanup.sh: refusing a path with a space or a percent sign: ${p}" >&2
		exit 1
		;;
	esac
	if [[ -L "${p}" ]]; then
		printf 'L+ %s - - - - %s\n' "${p}" "$(readlink "${p}")" >>"${conf}"
	elif [[ -d "${p}" ]]; then
		printf 'd %s %s %s %s - -\n' "${p}" "$(stat -c %a "${p}")" "$(stat -c %U "${p}")" "$(stat -c %G "${p}")" >>"${conf}"
	else
		rel=${p#/var/}
		mkdir -p "$(dirname "${factory}/${rel}")"
		cp -a "${p}" "${factory}/${rel}"
		printf 'C %s - - - - %s\n' "${p}" "${factory}/${rel}" >>"${conf}"
	fi
	n=$((n + 1))
done < <(find /var -mindepth 1 \( -path /var/cache -o -path /var/log \) -prune -o -print0 | sort -z)
find /var -mindepth 1 -maxdepth 1 ! -name cache ! -name log -exec rm -rf {} +
chmod 0644 "${conf}"
echo "final-cleanup.sh: ${n} /var entries moved to tmpfiles.d (${conf})"
